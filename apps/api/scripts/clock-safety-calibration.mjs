// One-off, SANDBOX ONLY. Tries every Clock request that is not a plain read against a record that cannot
// exist (id 0, empty body) and records what Clock did, so the dashboard's permission check knows which
// requests are safe to send to a hotel's real account.
//
//   pnpm --filter api build
//   node --env-file=.env scripts/clock-safety-calibration.mjs [--write]
//
// Needs CLOCK_SANDBOX_API_USER, CLOCK_SANDBOX_API_KEY, CLOCK_SANDBOX_PMS_API_URL and
// CLOCK_SANDBOX_SUBSCRIPTION_ID (and CLOCK_SANDBOX_ACCOUNT_ID); refuses to run against anything else.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const dist = new URL('../dist/integrations/clock/', import.meta.url);
const { ClockHttpClient } = await import(new URL('clock-http-client.js', dist));
const { CLOCK_API_CATALOG } = await import(new URL('clock-api-catalog.js', dist));

const url = new URL(process.env.CLOCK_SANDBOX_PMS_API_URL ?? 'https://invalid.example');
const credentials = {
  host: url.host,
  accountId: process.env.CLOCK_SANDBOX_ACCOUNT_ID ?? '172528',
  subscriptionId: process.env.CLOCK_SANDBOX_SUBSCRIPTION_ID ?? '16307',
  apiUser: process.env.CLOCK_SANDBOX_API_USER,
  apiKey: process.env.CLOCK_SANDBOX_API_KEY,
};
if (!credentials.apiUser || !credentials.apiKey || credentials.subscriptionId !== '16307') {
  console.error('Refusing to run: this only runs against the Clock sandbox (subscription 16307).');
  process.exit(1);
}

// These would change the shared sandbox in a way other tests depend on, so they are never tried.
const NEVER_TRIED = new Set([
  'POST base_api/webhook_subscription',
  'DELETE base_api/webhook_subscription',
  'POST pms_api/bookings/',
]);
const LARGE_LISTS = new Set([
  'GET base_api/folios',
  'GET base_api/2020-08-05/charge_logs',
  'GET base_api/2021-03-31/credit_item_logs',
  'GET base_api/folio_ledger',
]);
const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms));

const client = new ClockHttpClient();
const verdicts = {};
const rows = [];
for (const entry of CLOCK_API_CATALOG) {
  if (entry.api !== 'pms_api' && entry.api !== 'base_api') continue;
  const id = `${entry.method} ${entry.api}${entry.path}`;
  if (entry.method === 'GET' && !LARGE_LISTS.has(id)) continue;
  if (NEVER_TRIED.has(id)) {
    verdicts[id] = { verdict: 'unsafe', seen: 0 };
    rows.push([id, 'not tried', 'unsafe (changes shared sandbox state)']);
    continue;
  }
  const path = entry.path.replace(/:id/g, '0').replace(/:date/g, '2030-01-01');
  let status = 0;
  let message = '';
  let bytes = 0;
  try {
    const response = await client.request(credentials, {
      api: entry.api,
      method: entry.method,
      path,
      ...(entry.method === 'GET' ? { query: { id: '0' } } : { body: {} }),
      timeoutMs: 15000,
    });
    status = response.status;
    const text = JSON.stringify(response.body ?? '');
    bytes = text.length;
    message = (typeof response.body === 'object' && response.body && response.body.error) || '';
  } catch (error) {
    message = String(error.message);
  }
  // 403 only shows the sandbox lacks the right, so how Clock behaves when it IS granted stays unknown.
  const rejected =
    [400, 404, 405, 422].includes(status) || /param is missing|contract/i.test(String(message));
  const emptyList = entry.method === 'GET' && status >= 200 && status < 300 && bytes < 2000;
  const verdict = status === 403 ? 'unverified' : rejected || emptyList ? 'safe' : 'unsafe';
  verdicts[id] = { verdict, seen: status };
  rows.push([
    id,
    status || 'error',
    verdict + (verdict === 'unsafe' ? ` ${String(message).slice(0, 60)}` : ''),
  ]);
  await sleep(350);
}
for (const row of rows) console.log(String(row[1]).padEnd(7), row[2].padEnd(10), row[0]);
const counts = Object.values(verdicts).reduce(
  (n, v) => ((n[v.verdict] = (n[v.verdict] ?? 0) + 1), n),
  {},
);
console.log(counts);

if (process.argv.includes('--write')) {
  const body = `// What Clock did when each request was tried against a record that cannot exist, in the Clock SANDBOX.
// Generated by apps/api/scripts/clock-safety-calibration.mjs; do not edit by hand.
//   safe        The sandbox has the right and Clock answered "not found" or "invalid": nothing was changed.
//   unverified  The sandbox lacks the right (403), so what Clock does when it is granted was not observed.
//   unsafe      Clock accepted the request or failed unexpectedly: it cannot be tested without doing it.
// Only requests marked safe are ever sent to a hotel's real Clock account.
export const CLOCK_API_SAFETY: Record<string, { verdict: 'safe' | 'unverified' | 'unsafe'; seen: number }> = ${JSON.stringify(verdicts, null, 2)};
`;
  writeFileSync(
    fileURLToPath(new URL('../src/integrations/clock/clock-api-safety.ts', import.meta.url)),
    body,
  );
  console.log('Wrote clock-api-safety.ts');
}
